const IMAGE_EXT_RE = /\.(?:png|jpe?g|gif|svg|webp|avif|ico|bmp)(?:\?|#|$)/i;
const IMAGE_PREFIX_RE = /^(?:https?:|data:|blob:|\/|\.\/|\.\.\/)/i;

export function configForApp(app) {
    if (!app) return null;
    const name = app.name;
    if (ICON_CONFIG[name]) return ICON_CONFIG[name];

    if (app.iconImage) return { type: 'image', image: app.iconImage };
    const icon = app.icon;
    if (icon && (IMAGE_EXT_RE.test(icon) || IMAGE_PREFIX_RE.test(icon))) {
        return { type: 'image', image: icon };
    }

    return inferFromLegacyIcon(icon, name);
}

function inferFromLegacyIcon(faClass, name) {
    if (!faClass) return { glyph: 'grid', bg: ['#94A3B8', '#475569'] };
    const c = faClass.toLowerCase();
    if (c.includes('palette') || c.includes('paint')) return { glyph: 'palette', bg: ['#FF6FA8', '#FF3B73'] };
    if (c.includes('robot')) return { glyph: 'sparkles', bg: ['#7C5CFF', '#3D2BD9'] };
    if (c.includes('volume')) return { glyph: 'volume', bg: ['#FFB347', '#FF7E2D'] };
    if (c.includes('gamepad') || c.includes('game')) return { glyph: 'gamepad', bg: ['#34D399', '#0F766E'] };
    if (c.includes('film') || c.includes('movie')) return { glyph: 'film', bg: ['#FB7185', '#9D174D'] };
    if (c.includes('discord')) return { glyph: 'discord', bg: ['#7289DA', '#4254A8'] };
    if (c.includes('youtube')) return { glyph: 'youtube', bg: ['#FF3D3D', '#C40A0A'], glyphColor: '#FFFFFF' };
    if (c.includes('gear') || c.includes('cog')) return { glyph: 'settings', bg: ['#A8B0BC', '#5B6472'] };
    if (c.includes('brush')) return { glyph: 'brush', bg: ['#F472B6', '#A21CAF'] };
    if (c.includes('wand')) return { glyph: 'wand', bg: ['#FACC15', '#D97706'] };
    if (c.includes('note') || c.includes('sticky')) return { glyph: 'note', bg: ['#FCD34D', '#F59E0B'] };
    if (c.includes('info') || c.includes('circle-info')) return { glyph: 'info', bg: ['#60A5FA', '#1D4ED8'] };
    if (c.includes('tiktok')) return { glyph: 'tiktok', bg: ['#0F0F12', '#1A1A1F'] };
    if (c.includes('js')) return { glyph: 'js', bg: ['#FFE25A', '#F0CA17'] };
    if (c.includes('python')) return { glyph: 'python', bg: ['#FFFFFF', '#E5E7EB'] };
    if (c.includes('globe')) return { glyph: 'globe', bg: ['#38BDF8', '#0369A1'] };
    if (c.includes('music')) return { glyph: 'music', bg: ['#F97316', '#EA580C'] };
    if (c.includes('folder')) return { glyph: 'folder', bg: ['#60A5FA', '#2563EB'] };
    if (c.includes('shield')) return { glyph: 'shield', bg: ['#FB7185', '#BE123C'] };
    return { glyph: 'grid', bg: ['#94A3B8', '#475569'] };
}
